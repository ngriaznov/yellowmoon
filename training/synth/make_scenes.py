def merged_index(out: Path, new: list[dict]) -> list[dict]:
    """The scene index after a run: ``new`` (this run's recipes) plus the entries an earlier run listed whose files are
    still there, so a run limited by ``--only`` (or a default run after ``--full``) does not forget the other scenes."""
    try:
        old = json.loads((out / "index.json").read_text())["scenes"]
    except (OSError, ValueError, KeyError, TypeError):
        old = []
    ids = {e["id"] for e in new}
    keep = [e for e in old if isinstance(e, dict) and e.get("id") not in ids and (out / f"{e.get('id')}.json").exists()]
    return sorted(keep + new, key=lambda e: e["id"])


def human(n: float) -> str:
    for unit in ("B", "kB", "MB", "GB"):
        if n < 1000 or unit == "GB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1000.0
    return str(n)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", type=Path, default=paths.TESTDATA / "synthetic" / "scenes", help="output folder")
    ap.add_argument("--full", action="store_true", help="also the full-size and evaluation scenes")
    ap.add_argument("--force", action="store_true", help="rewrite files that are up to date")
    ap.add_argument("--only", action="append", default=[], metavar="TEXT", help="only recipes whose stem contains TEXT")
    ap.add_argument("--list", action="store_true", help="list the recipes and exit")
    ap.add_argument("--write-manifest", type=Path, metavar="FILE")
    ap.add_argument("--check-manifest", type=Path, metavar="FILE")
    args = ap.parse_args(argv)

    if args.write_manifest:
        write_manifest(args.write_manifest)
        n = len(rc.manifest(full=True)["entries"])
        print(f"wrote {n} synthetic entries to {args.write_manifest}")
        return 0
    if args.check_manifest:
        ok = write_manifest(args.check_manifest, check=True)
        print("manifest is up to date" if ok else f"{args.check_manifest} differs from the recipes: run --write-manifest")
        return 0 if ok else 1

    all_recipes = rc.recipes(args.full)
    chosen = [(i, r) for i, r in enumerate(all_recipes) if not args.only or any(t in r.stem for t in args.only)]
    if args.list:
        for i, r in chosen:
            print(f"{i:3d}  {r.stem}  {','.join(r.variants)}")
        print(f"{len(chosen)} mosaics, {sum(len(r.variants) for _, r in chosen)} ARW files")
        return 0

    paths.require_sources()
    # group by (scene, light, curves) so renders are reused, keeping the recipe index for the capture time
    order = sorted(chosen, key=lambda ir: (ir[1].scene, ir[1].light, sp.BODIES[ir[1].body].curves, ir[0]))
    ctx = Context()
    rows = []
    t0 = time.time()
    for n, (i, r) in enumerate(order, 1):
        row = generate(r, i, args.out, ctx, args.force)
        rows.append(row)
        print(f"[{n:3d}/{len(order)}] {row['status']:10s} {row['seconds']:5.1f} s  {human(row['bytes']):>9s}  {r.stem}", flush=True)
    index = merged_index(
        args.out,
        [{"id": r.stem, "recipe_hash": recipe_hash(r, i), "variants": list(r.variants), "tier": r.tier} for i, r in chosen],
    )
    (args.out / "index.json").write_text(json.dumps({"format": "ym-synth-index", "version": FORMAT_VERSION,
                                                     "generator_version": GENERATOR_VERSION, "scenes": index}, indent=1) + "\n")
    total = sum(r["bytes"] for r in rows)
    print(f"{len(rows)} mosaics ({sum(r['status'] == 'written' for r in rows)} written), {human(total)} in {args.out}, "
          f"{time.time() - t0:.0f} s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
