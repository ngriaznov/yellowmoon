def recipe_hash(recipe: rc.Recipe, index: int) -> str:
    blob = json.dumps({"recipe": recipe.to_json(), "version": GENERATOR_VERSION, "index": index}, sort_keys=True)
    return hashlib.sha256(blob.encode()).hexdigest()[:16]


def awb_sigma(light: sp.SceneLight) -> float:
    """Spread (log gain, per channel) of the simulated automatic white balance error."""
    return {"mixed": 0.04, "fluorescent": 0.03, "led": 0.03}.get(light.klass, 0.02)


def build_sidecar(recipe: rc.Recipe, index: int, rendered: Rendered, mosaic: np.ndarray,
                  jpeg: bytes, jpeg_size: tuple[int, int], k_mode: float, mode: sn.Mode, nm: sn.NoiseModel,
                  gains_true: np.ndarray, wb_levels: list[int], awb_err: np.ndarray, sigma: float) -> dict:
    scene, light, body, lt_ = rendered.scene, rendered.light, rendered.body, rendered.truth
    shutter, fnum, ev_iso = exposure_metadata(light.ev100, recipe.iso)
    probes = []
    for p, s_w in zip(scene.probes, rendered.probe_s):
        v = lt_.probe_values(p.mixture, p.m, s_w)
        cam = np.array(v.pop("camera_response"))
        dn = k_mode * cam
        entry = {
            "name": p.name, "group": p.group, "role": p.role, "rect": list(p.rect), "interior": list(p.interior),
            "irradiance": p.m,
            "reflectance": [[scene.bank.names[i], wt] for i, wt in p.mixture],
            "camera_dn_above_black": dn.tolist(),
            "clipped_channels": [bool(x >= mode.span) for x in dn],
            **v,
        }
        if light.kind == "mixed":
            entry["mix_weight_right_light"] = s_w
        if p.info:
            entry["info"] = p.info
        probes.append(entry)
    left_right = None
    if light.kind == "mixed":
        left_right = {
            "left": light.components[0], "right": light.components[1],
            "weight_of_right_light": (
                f"smoothstep((x / width - {ly.MIX_START:g}) / {ly.MIX_END - ly.MIX_START:.6g}), per column"
            ),
            "reference_light": "equal mixture (the image-wide average); white balance and ARRI CCT are those of the mixture",
        }
    g = tr.gamut_matrices()
    truth = {
        "synthetic": True,
        "notice": NOTICE + (EVAL_NOTICE if recipe.scene == "eval" else ""),
        "light": {
            "token": light.token, "name": light.name, "kind": light.kind, "class": light.klass,
            "class_probabilities": dict(light.class_probs), "cct_k": light.cct_k, "cct_convention": light.cct_convention,
            "xy": sp.cie_xy(light.spd),
            "w_true_camera_rgb": lt_.w_true.tolist(),
            "camera_profile": body.curves,
            "camera_profile_is_stand_in": not body.own_curves,
            "w_alexa_native": lt_.w_alexa.tolist(),
            "mixed": left_right,
        },
        "as_shot": {
            "gains_true": gains_true.tolist(),
            "wb_rggb_1024": wb_levels,
            "log_gain_error_rb": awb_err.tolist(),
            "sigma": sigma,
            "note": "SR2 white balance = the true gains times exp(error), the error drawn like an automatic white balance",
        },
        "noise": nm.to_json(),
        "exposure": {
            "reference_probe": "neutral-0.18",
            "grey_fraction_of_range": sn.GREY_FRACTION,
            "exposure_comp_ev": recipe.ev_comp,
            "dn_per_response_unit": k_mode,
            "scene_ev100": light.ev100,
            "ev_at_iso": ev_iso,
        },
        "arri": {
            "cct_k": light.cct_k,
            "native_balanced_to_awg3": tr.native_to_awg3(light.cct_k).tolist(),
            "awg3_to_awg4": g["awg3_to_awg4"].tolist(),
            "conventions": (
                "docs/02 C3-C6: ALEXA estimate responses, white balance to the light, ARRI matrix at the CCT "
                "(mired interpolation) to AWG3, exact AWG3 to AWG4, LogC4. Values are reflectance-referred: a "
                "perfect white under the light is [1, 1, 1], the 18% grey [0.18, ...]. Compare after normalising "
                "to the grey patch; highlight values are the unclipped truth."
            ),
        },
        "bank": {"names": scene.bank.names, "sources": scene.bank.sources},
        "probes": probes,
        "features": scene.features,
        "scene": {
            "name": scene.name, "width": scene.W, "height": scene.H, "scale": scene.scale,
            "virtual_size": [ly.VIRTUAL_W, ly.VIRTUAL_H], "psf_sigma_px": ly.PSF_SIGMA_PX,
            "hue_patches": scene.hue_names,
        },
    }
    writer = {
        "make": "SONY",
        "model": body.model,
        "model_id": body.model_id,
        "lens_model": body.lens,
        "focal_length_mm": body.focal_mm,
        "iso": recipe.iso,
        "exposure_time": list(shutter),
        "f_number": list(fnum),
        "exposure_comp_ev": recipe.ev_comp,
        "capture_time": rc.capture_time(index),
        "sr2": {
            "black": [mode.black << mode.shift] * 4,
            "white": [sn.MODE_14.white] * 3,
            "wb_rggb": wb_levels,
            "note": "levels are written on the 14-bit scale, as Sony does; the decoder shifts them for 12-bit data",
        },
        "decoded_levels": {"black": mode.black, "white": mode.white},
        "preview": {
            "file": f"{recipe.stem}.jpg", "width": jpeg_size[0], "height": jpeg_size[1], "bytes": len(jpeg),
            "synthetic": True,
            "note": "made-up sRGB rendering for auto-exposure comparisons, not a camera rendering (preview.py)",
        },
        "variants": list(recipe.variants),
        "lens_tables": "neutral (all zero: the scene has no lens effects)",
        "software": f"{body.model} v1.00 (Yellowmoon synthetic test file)",
    }
    return {
        "format": "ym-synth-scene",
        "format_version": FORMAT_VERSION,
        "id": recipe.stem,
        "tier": recipe.tier,
        "synthetic": True,
        "notice": truth["notice"],
        "generator": {
            "name": "training.synth.make_scenes", "version": GENERATOR_VERSION,
            "recipe": recipe.to_json(), "recipe_hash": recipe_hash(recipe, index), "recipe_index": index,
        },
        "mosaic": {
            "file": f"{recipe.stem}.bin", "encoding": "u16 little-endian, row-major, black level included",
            "width": int(mosaic.shape[1]), "height": int(mosaic.shape[0]), "cfa": recipe.cfa, "bits": mode.bits,
            "black": mode.black, "white": mode.white,
            "sha256": hashlib.sha256(mosaic.astype("<u2").tobytes()).hexdigest(),
            "clipped_fraction": sn.clipped_fraction(mosaic, mode),
        },
        "writer": writer,
        "truth": truth,
    }


def up_to_date(side: Path, binf: Path, jpgf: Path, want_hash: str) -> bool:
    """True when the sidecar carries this recipe hash and the two other files have the sizes it states."""
    try:
        doc = json.loads(side.read_text())
        m = doc["mosaic"]
        return (
            doc["generator"]["recipe_hash"] == want_hash
            and binf.stat().st_size == m["width"] * m["height"] * 2
            and jpgf.stat().st_size == doc["writer"]["preview"]["bytes"]
        )
    except (OSError, ValueError, KeyError):
        return False


def generate(recipe: rc.Recipe, index: int, out: Path, ctx: Context, force: bool) -> dict:
    """Writes the files of one recipe; returns a summary row."""
    t0 = time.time()
    side = out / f"{recipe.stem}.json"
    binf, jpgf = out / f"{recipe.stem}.bin", out / f"{recipe.stem}.jpg"
    want = recipe_hash(recipe, index)
    if not force and side.exists() and binf.exists() and jpgf.exists() and up_to_date(side, binf, jpgf, want):
        return {"stem": recipe.stem, "status": "up to date",
                "bytes": binf.stat().st_size + jpgf.stat().st_size + side.stat().st_size, "seconds": 0.0}
    body = sp.BODIES[recipe.body]
    mode = sn.MODES[recipe.bits]
    rendered = ctx.render(recipe.scene, recipe.light, recipe.body)
    scene, lt_ = rendered.scene, rendered.truth

    grey = next(p for p in scene.probes if p.role == "grey_reference")
    s_grey = rendered.probe_s[scene.probes.index(grey)]
    grey_resp = lt_.local_response("camera", grey.mixture, s_grey)
    k_mode = sn.exposure_scale(grey_resp[1], mode, recipe.ev_comp)
    k14 = sn.exposure_scale(grey_resp[1], sn.MODE_14, recipe.ev_comp)

    nm = sn.noise_model(body, recipe.iso, mode)
    clean = sn.cfa_mosaic(rendered.canvas * np.float32(k_mode), recipe.cfa)
    rng = np.random.default_rng(seed_of(recipe.stem, "noise"))
    mosaic = sn.sample(clean, mode, nm, rng)
    del clean

    # as-shot white balance: the true gains perturbed like an automatic white balance
    gains_true = np.array([1.0 / lt_.w_true[0], 1.0, 1.0 / lt_.w_true[2]])
    sigma = awb_sigma(rendered.light)
    err = np.random.default_rng(seed_of(recipe.stem, "awb")).normal(0.0, sigma, 2)
    gains = gains_true * np.array([np.exp(err[0]), 1.0, np.exp(err[1])])
    wb_levels = [int(round(1024 * gains[0])), 1024, 1024, int(round(1024 * gains[2]))]
    gains_used = np.array([wb_levels[0] / 1024.0, 1.0, wb_levels[3] / 1024.0])

    # the embedded JPEG
    raw_small = ctx.small_raw(rendered, k14)
    matrix = pv.camera_to_srgb_matrix(rendered.light.spd, sp.camera_curves(body))
    rgb8 = pv.render(raw_small, gains_used, matrix)
    jpeg = pv.encode_jpeg(rgb8)

    out.mkdir(parents=True, exist_ok=True)
    side_doc = build_sidecar(recipe, index, rendered, mosaic, jpeg, (rgb8.shape[1], rgb8.shape[0]), k_mode, mode, nm,
                             gains_true, wb_levels, err, sigma)
    for path, data in ((binf, mosaic.astype("<u2").tobytes()), (jpgf, jpeg)):
        tmp = path.with_suffix(path.suffix + ".tmp")
        tmp.write_bytes(data)
        os.replace(tmp, path)
    tmp = side.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(round_floats(side_doc), separators=(",", ":"), allow_nan=False))
    os.replace(tmp, side)  # the sidecar last: its presence means the set of three is complete
    return {"stem": recipe.stem, "status": "written", "bytes": binf.stat().st_size + jpgf.stat().st_size + side.stat().st_size,
            "seconds": time.time() - t0}


