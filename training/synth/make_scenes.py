"""Generates the synthetic scenes: raw mosaics, embedded JPEGs and ground-truth sidecars.

    python3 -m training.synth.make_scenes --out testdata/synthetic/scenes            # the default (CI) set
    python3 -m training.synth.make_scenes --out testdata/synthetic/scenes --full     # + full-size and evaluation scenes
    python3 -m training.synth.make_scenes --list [--full]                            # what would be written
    python3 -m training.synth.make_scenes --write-manifest tools/golden/manifest.json
    python3 -m training.synth.make_scenes --check-manifest tools/golden/manifest.json

For each recipe (``recipes.py``) it writes next to each other, in the output folder::

    <stem>.bin    the mosaic: little-endian u16, row-major, width x height, black level included
    <stem>.jpg    the embedded camera JPEG (synthetic rendering; see preview.py)
    <stem>.json   the sidecar: how to write the ARW (``writer``) and the ground truth (``truth``)

Output is a pure function of the recipe, the code version and the library versions: seeds come from the file stem.
Re-running skips what is up to date (same recipe hash, files present); ``--force`` rewrites everything.
Format and physics: ``training/synth/README.md``.
"""

