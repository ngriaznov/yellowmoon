# Standard shutter speeds (seconds), a third of a stop apart, for the exposure metadata.
_SHUTTERS = [
    1 / 8000, 1 / 6400, 1 / 5000, 1 / 4000, 1 / 3200, 1 / 2500, 1 / 2000, 1 / 1600, 1 / 1250, 1 / 1000, 1 / 800, 1 / 640,
    1 / 500, 1 / 400, 1 / 320, 1 / 250, 1 / 200, 1 / 160, 1 / 125, 1 / 100, 1 / 80, 1 / 60, 1 / 50, 1 / 40, 1 / 30,
    1 / 25, 1 / 20, 1 / 15, 1 / 13, 1 / 10, 1 / 8, 1 / 6, 1 / 5, 1 / 4, 0.3, 0.4, 0.5, 0.6, 0.8, 1.0, 1.3, 1.6, 2.0,
    2.5, 3.2, 4.0,
]
_APERTURES = [(8.0, (80, 10)), (5.6, (56, 10)), (4.0, (40, 10)), (2.8, (28, 10)), (11.0, (110, 10)), (16.0, (160, 10))]  # noqa: E501


def seed_of(stem: str, tag: str) -> int:
    """A stable 64-bit seed for a file and a purpose."""
    return int.from_bytes(hashlib.sha256(f"{GENERATOR_VERSION}/{stem}/{tag}".encode()).digest()[:8], "little")


def exposure_metadata(ev100: float, iso: int) -> tuple[tuple[int, int], tuple[int, int], float]:
    """(shutter as a fraction, f-number as a fraction, EV at the ISO) from the grey's brightness at ISO 100.

    Meter equation ``t = N^2 / 2^(EV100 + log2(ISO / 100))``. The aperture is the first of f/8, 5.6, 4, 2.8 that gives
    a hand-holdable 1/60 s or shorter (f/2.8 if none does); a scene so bright that f/8 would need less than 1/8000 s
    gets f/11 or f/16."""
    ev_iso = ev100 + float(np.log2(iso / 100.0))
    n, frac = next(((n, f) for n, f in _APERTURES[:4] if n * n / 2.0**ev_iso <= 1 / 60), _APERTURES[3])
    if n == 8.0 and n * n / 2.0**ev_iso < 1 / 8000:
        for n, frac in _APERTURES[4:]:
            if n * n / 2.0**ev_iso >= 1 / 8000:
                break
    t = n * n / 2.0**ev_iso
    nearest = min(_SHUTTERS, key=lambda s_: abs(np.log2(s_ / t)))
    # EXIF stores a rational: 1/N below a quarter of a second, tenths above.
    shutter = (1, int(round(1.0 / nearest))) if nearest < 0.25 else (int(round(nearest * 10)), 10)
    return shutter, frac, ev_iso


def round_floats(obj, digits: int = 9):
    """Recursively rounds floats (and numpy scalars) to ``digits`` significant digits so the sidecars are compact
    and stable across platforms."""
    if isinstance(obj, dict):
        return {str(k): round_floats(v, digits) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [round_floats(v, digits) for v in obj]
    if isinstance(obj, (np.floating, float)):
        x = float(obj)
        return float(f"{x:.{digits}g}") if np.isfinite(x) else x
    if isinstance(obj, np.integer):
        return int(obj)
    if isinstance(obj, np.ndarray):
        return round_floats(obj.tolist(), digits)
    if isinstance(obj, np.bool_):
        return bool(obj)
    return obj


