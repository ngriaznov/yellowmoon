def write_manifest(path: Path, check: bool = False) -> bool:
    """Writes (or checks) the synthetic entries of the golden manifest, keeping any other entries."""
    existing: dict = {}
    if path.exists():
        existing = json.loads(path.read_text())
    others = [e for e in existing.get("entries", []) if not str(e.get("tier", "")).startswith("synthetic")]
    doc = {**MANIFEST_HEADER}
    for key, value in existing.items():
        if key not in doc and key != "entries":
            doc[key] = value
    doc["entries"] = rc.manifest(full=True)["entries"] + others
    text = json.dumps(doc, indent=2) + "\n"
    if check:
        return path.exists() and path.read_text() == text
    path.write_text(text)
    return True


