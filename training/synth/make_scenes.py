@dataclass
class Rendered:
    """A scene under one light seen by one body, noise-free, in camera response units, PSF applied."""

    scene: ly.Scene
    light: sp.SceneLight
    body: sp.Body
    truth: tr.LightTruth
    canvas: np.ndarray = field(repr=False)  # (H, W, 3) float32
    probe_s: list[float] = field(default_factory=list)  # mixed-light weight of each probe


class Context:
    """Caches scenes, lights and the latest render (a full-size canvas is 300 MB, so only one is kept)."""

    def __init__(self) -> None:
        self.lights = sp.all_lights()
        self._scenes: dict[str, ly.Scene] = {}
        self._irr: dict[str, np.ndarray] = {}
        self._rendered: tuple[tuple, Rendered] | None = None
        self._preview_cache: tuple[tuple, np.ndarray] | None = None

    def scene(self, name: str) -> ly.Scene:
        if name not in self._scenes:
            if name == "eval":
                patches = sp.evaluation_patches()
            else:
                patches = sp.training_patches()
            self._scenes[name] = ly.Scene(name, rc.SCENE_SCALE[name], patches, evaluation=(name == "eval"))
            self._irr[name] = self._scenes[name].irradiance()
        return self._scenes[name]

    def render(self, scene_name: str, light_token: str, model: str) -> Rendered:
        body = sp.BODIES[model]
        key = (scene_name, light_token, body.curves)
        if self._rendered is not None and self._rendered[0] == key:
            r = self._rendered[1]
            if r.body.model != body.model:  # same curves (the A1 and the A7R IV): the truth object depends on the body
                r = Rendered(r.scene, r.light, body, self._truth(r.scene, r.light, body), r.canvas, r.probe_s)
            return r
        scene = self.scene(scene_name)
        light = self.lights[light_token]
        self._rendered = None  # free the previous canvas before allocating the next
        self._preview_cache = None
        curves = sp.camera_curves(body)
        spectra = scene.bank.spectra
        if light.kind == "mixed":
            left_spd, right_spd = light.component_spds
            refl_l = scene.render_refl(tr.responses(spectra, left_spd, curves))
            refl_r = scene.render_refl(tr.responses(spectra, right_spd, curves))
            w = scene.mix_weight().astype(np.float32)[None, :, None]
            refl = (1.0 - w) * refl_l + w * refl_r
            del refl_l, refl_r
        else:
            refl = scene.render_refl(tr.responses(spectra, light.spd, curves))
        refl *= self._irr[scene_name][..., None]
        canvas = ly.apply_psf(refl)
        del refl
        truth = self._truth(scene, light, body)
        probe_s = self._probe_weights(scene, light)
        r = Rendered(scene, light, body, truth, canvas, probe_s)
        self._rendered = (key, r)
        return r

    def _truth(self, scene: ly.Scene, light: sp.SceneLight, body: sp.Body) -> tr.LightTruth:
        lr = light.component_spds if light.kind == "mixed" else None
        return tr.LightTruth(light, body, scene.bank.spectra, left_right=lr)

    @staticmethod
    def _probe_weights(scene: ly.Scene, light: sp.SceneLight) -> list[float]:
        if light.kind != "mixed":
            return [0.0] * len(scene.probes)
        w = scene.mix_weight()
        out = []
        for p in scene.probes:
            x, _, bw, _ = p.interior
            out.append(float(w[x : x + bw].mean()))
        return out

    def small_raw(self, rendered: Rendered, k14: float) -> np.ndarray:
        """The noise-free raw image at the preview size (1248 x 832), normalised to the 14-bit range."""
        key = (rendered.scene.name, rendered.light.token, rendered.body.curves, k14)
        if self._preview_cache is not None and self._preview_cache[0] == key:
            return self._preview_cache[1]
        factor = max(int(round(rendered.scene.scale)), 1) if rendered.scene.scale >= 1 else 1
        raw = pv.block_mean(rendered.canvas, factor) * (k14 / sn.MODE_14.span)
        self._preview_cache = (key, raw.astype(np.float32))
        return self._preview_cache[1]


