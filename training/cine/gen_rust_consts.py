"""Writes crates/ym-color/src/display/cine/consts.rs from constants.json (the cine rendering's constants, docs/02 C12).

The JSON is the source of truth. The Rust table is generated from it, never edited by hand, and the test
``cine_constants_equal_the_json`` (crates/ym-color/src/display/cine.rs) fails if the two differ by one digit.
After a refit of ``constants.json``, run

    python3 training/cine/gen_rust_consts.py

and regenerate the fixture with ``make_vectors.py``. Nothing else in the Rust code changes: the GPU kernel's
constants are written from this table when the shader source is built (``ym-gpu``, ``kernels/color.rs``).

Python is for tooling only; the app and ``ym`` never run it.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(REPO, "crates", "ym-color", "src", "display", "cine", "consts.rs")

# The harmonic constants are grouped into arrays [c1, s1, c2, s2, c3, s3], in the order the equations use.
GROUPS = ["gh_b0", "gh_bh", "dt_b0", "dt_bh", "rh_b0", "rh_bh"]
SUFFIX = ["c1", "s1", "c2", "s2", "c3", "s3"]

# What each scalar means, for the doc comment of its constant (the long form is the table in docs/02).
DOC = {
    "la": "ln a: the exponent `a = e^la` of the tone curve (`Ys^-a`).",
    "lc": "ln c: `c = e^lc` in `H = (1 + c Ys^-a)^-b`.",
    "lb": "ln b: `b = e^lb`, the exponent of `H`.",
    "wc": "Half-width of the soft clip at the top of the tone curve.",
    "uw": "White level: stops over grey at which the neutral axis reaches exactly 1.0 (set by hand).",
    "kap": "`(1 + wc) / H(0.18 2^uw)`, derived from `la`, `lc`, `lb`, `wc` and `uw`.",
    "lgpk": "ln of the chroma gain in the deepest shadows.",
    "lYc": "ln of the scene luminance at which the chroma gain has fallen to half.",
    "gb": "Steepness of that fall.",
    "lchih": "ln of the relative chroma at which the hue terms are half on.",
    "rp": "Exponent of the chroma envelope of the lightness term.",
    "r_dark": "Lightness change (ln) added below `r_Yd` for strongly coloured pixels.",
    "r_Yd": "Level (stops over grey) at which that extra change fades out.",
    "r_hi": "Lightness change (ln) of strongly coloured pixels at every level.",
    "r_chi": "ln of the relative chroma at which the lightness term is half on.",
    "lklo": "ln `kl`: where the soft floor of a channel starts, relative to the display luminance.",
    "lkhi": "ln `kh`: half-width of the soft ceiling.",
    "rho": "The luminance floor: `Yf = rho` times the distance of the chromaticity from the neutral axis (by hand).",
    "wfrac": "Width of the smooth maximum of the luminance floor, in units of `Yf` (by hand).",
    "chi_k": "Relative chroma at which the soft limit starts (by hand).",
    "chi_m": "The value the limited chroma tends to (by hand).",
}


def literal(v):
    """A Rust f64 literal that parses back to exactly the JSON number."""
    s = repr(float(v))
    if "e" not in s and "." not in s:
        s += ".0"
    return s


def main(out=OUT, source=None):
    with open(source or os.path.join(HERE, "constants.json")) as f:
        consts = json.load(f)
    lines = [
        "//! The constants of the cine rendering. GENERATED by `training/cine/gen_rust_consts.py` from",
        "//! `training/cine/constants.json`; do not edit by hand (the test `cine_constants_equal_the_json` fails on a",
        "//! difference of one digit). `docs/02-colour-pipeline.md`, C12, *Constants*, describes every name.",
        "",
        "#![allow(clippy::unreadable_literal, clippy::excessive_precision)]",
        "",
    ]
    names = []
    for key, value in consts.items():
        rust = key.upper()
        names.append((key, rust))
        in_group = any(key.startswith(g + "_") for g in GROUPS)
        doc = DOC.get(key)
        if in_group:
            q, base, term = key.split("_")
            what = {"gh": "log of the chroma factor", "dt": "hue turn (radians)", "rh": "log of the lightness factor"}[q]
            part = "the part that does not depend on level" if base == "b0" else "the part that comes in above about +1.5 stops"
            doc = f"Hue harmonic `{term}` of the {what}, {part}."
        lines.append(f"/// {doc}")
        lines.append(f"pub const {rust}: f64 = {literal(value)};")
    lines.append("")
    for g in GROUPS:
        members = ", ".join(f"{g.upper()}_{s.upper()}" for s in SUFFIX)
        lines.append(f"/// The six harmonic constants `{g}` as `[c1, s1, c2, s2, c3, s3]`.")
        lines.append(f"pub const {g.upper()}: [f64; 6] = [{members}];")
    lines.append("")
    lines.append("/// Every constant by its name in `constants.json`, for the test that compares the table with the file.")
    lines.append(f"pub const TABLE: [(&str, f64); {len(names)}] = [")
    for key, rust in names:
        lines.append(f'    ("{key}", {rust}),')
    lines.append("];")
    lines.append("")
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {out} ({len(names)} constants)")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else OUT, sys.argv[2] if len(sys.argv) > 2 else None)
