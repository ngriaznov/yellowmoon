#!/usr/bin/env python3
"""Writes the fixture of crates/ym-color/src/blur_py_fixture.rs: outputs of blur_ref.py (the sketch) on a small
deterministic scene, to check ym_color::blur against (BL-03). Run: python3 -I blur_fixture.py > blur_py_fixture.rs

The scene is built by an integer hash so the Rust test rebuilds it exactly. Two differences between the sketch and the
spec's exact kernels are handled here, and are the reason the Motion bound is looser:
  * the sketch's FFT convolution flips the kernel, the spec gathers (k_p(q) = Table(q - p)): for an aperture that is not
    point-symmetric (an odd number of blades) the flipped table is passed to the sketch;
  * the sketch's line kernel drops 8 point samples per pixel of length into the nearest pixel, the oracle clips the
    segment exactly: here the sketch's kernel is taken at 512 samples per pixel, where it has converged to the clip.
"""
import os
import sys
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import blur_ref as B

W, H = 64, 48


def hash01(i):
    return ((i * 2654435761 + 12345) % 4294967296) / 4294967296.0


def scene():
    X = np.zeros((H, W, 3))
    for y in range(H):
        for x in range(W):
            for c in range(3):
                X[y, x, c] = 0.02 + 1.98 * hash01((y * 131 + x * 31 + c * 17 + 7) * 3 + c)
    X[20:23, 30:33] = 300.0
    return X


def mask():
    m = np.zeros((H, W))
    for y in range(H):
        for x in range(W):
            m[y, x] = min(1.0, max(0.0, (x - 20.0) / 24.0)) * (1.0 if y < 40 else 0.5)
    m[:, :20] = 0.0
    m[:, 44:] = 1.0
    return m


CASES = [
    ("soft", dict(radius=100)),
    ("soft", dict(radius=100, respect=False)),
    ("lens", dict(radius=100, blades=0)),
    ("lens", dict(radius=100, blades=6, rotation=10.0, highlights=0.5)),
    ("lens", dict(radius=100, blades=5, rotation=20.0, highlights=0.0)),
    ("motion", dict(length=100, angle=30.0)),
    ("motion", dict(length=100, angle=0.0)),
    ("zoom", dict(amount=100, centre=(0.3, 0.6))),
]
PIX = [(20, 30), (21, 31), (22, 32), (10, 25), (12, 45), (25, 20), (30, 44), (35, 10), (5, 60), (0, 0), (47, 63), (44, 50), (18, 29), (24, 33), (41, 28), (8, 38)]


def run(kind, kw, X, m):
    if kind == "lens" and kw.get("blades", 0) % 2 == 1:
        orig = B.aperture_kernel
        B.aperture_kernel = lambda *a, **k: orig(*a, **k)[::-1, ::-1]
        try:
            return B.blur_node(X, m, kind, **kw)
        finally:
            B.aperture_kernel = orig
    if kind == "motion":
        orig = B.line_kernel
        B.line_kernel = lambda length, angle: orig(length, angle, ss=512)
        try:
            return B.blur_node(X, m, kind, **kw)
        finally:
            B.line_kernel = orig
    return B.blur_node(X, m, kind, **kw)


if __name__ == "__main__":
    X, m = scene(), mask()
    print("// Generated by design/blur/html/blur_fixture.py from blur_ref.py (f64). Not edited by hand.")
    print("/// (case index, sum of all outputs, [(y, x, [r, g, b])]) per case of `blur_fixture.py`.")
    print("#[allow(clippy::excessive_precision, clippy::type_complexity)]")
    print("const PY_FIXTURE: [(usize, f64, [(usize, usize, [f64; 3]); 16]); %d] = [" % len(CASES))
    for i, (kind, kw) in enumerate(CASES):
        o = run(kind, kw, X, m)
        rows = ", ".join("(%d, %d, [%r, %r, %r])" % (y, x, *map(float, o[y, x])) for (y, x) in PIX)
        print("    (%d, %r, [%s])," % (i, float(o.sum()), rows))
    print("];")
