#[test]
fn sharma_wu_dalal_34_pairs_to_1e_4() {
    assert_eq!(SHARMA.len(), 34);
    let mut worst = 0.0_f64;
    for (i, (lab1, lab2, want)) in SHARMA.iter().enumerate() {
        let got = delta_e_2000(*lab1, *lab2);
        let err = (got - want).abs();
        worst = worst.max(err);
        assert!(
            err < 1e-4,
            "pair {}: got {got:.6}, published {want:.4}",
            i + 1
        );
        // CIEDE2000 is symmetric in its arguments.
        let swapped = delta_e_2000(*lab2, *lab1);
        assert!(
            (got - swapped).abs() < 1e-9,
            "pair {} not symmetric: {got} vs {swapped}",
            i + 1
        );
    }
    println!("max |dE00 - published| over the 34 Sharma pairs: {worst:e}");
}

#[test]
fn pair_14_tie_break_is_the_published_one() {
    // Pair 14 has hue angles exactly 180 degrees apart; the published value takes the |dh| <= 180 branch.
    let (lab1, lab2, want) = SHARMA[13];
    assert_eq!(lab1, [50.0, -0.0010, 2.4900]);
    assert!((delta_e_2000(lab1, lab2) - want).abs() < 1e-4);
}

