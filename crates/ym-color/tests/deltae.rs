#[test]
fn xyz_lab_matches_color_science_and_round_trips() {
    let white = d65_white_xyz();
    for (xyz, want) in COLOR_XYZ_LAB {
        let lab = xyz_to_lab(xyz, white);
        for k in 0..3 {
            assert!(
                (lab[k] - want[k]).abs() < 1e-8,
                "{xyz:?}: {lab:?} vs {want:?}"
            );
        }
        let back = lab_to_xyz(lab, white);
        for k in 0..3 {
            assert!((back[k] - xyz[k]).abs() < 1e-14, "{xyz:?}: {back:?}");
        }
    }
    // The linear segment below epsilon round-trips too, and joins continuously at epsilon.
    for y in [
        0.0,
        1e-6,
        1e-3,
        216.0 / 24389.0 - 1e-9,
        216.0 / 24389.0 + 1e-9,
        0.5,
    ] {
        let xyz = [y * white[0], y, y * white[2]];
        let back = lab_to_xyz(xyz_to_lab(xyz, white), white);
        for k in 0..3 {
            assert!((back[k] - xyz[k]).abs() < 1e-14);
        }
    }
    let lo = xyz_to_lab([0.0, 216.0 / 24389.0 - 1e-12, 0.0], white)[0];
    let hi = xyz_to_lab([0.0, 216.0 / 24389.0 + 1e-12, 0.0], white)[0];
    assert!((lo - hi).abs() < 1e-8);
}

#[test]
fn delta_e_76_and_weights() {
    assert!((delta_e_76([50.0, 0.0, 0.0], [53.0, 4.0, 0.0]) - 5.0).abs() < 1e-14);
    // Doubling kL halves the pure-lightness difference.
    let a = [50.0, 0.0, 0.0];
    let b = [52.0, 0.0, 0.0];
    let unit = delta_e_2000(a, b);
    let weighted = delta_e_2000_weighted(a, b, 2.0, 1.0, 1.0);
    assert!((unit / weighted - 2.0).abs() < 1e-12);
}

#[test]
fn percentile_and_summary() {
    let v = [3.0, 1.0, 2.0, 5.0, 4.0];
    assert_eq!(percentile(&v, 0.0), Some(1.0));
    assert_eq!(percentile(&v, 100.0), Some(5.0));
    assert_eq!(percentile(&v, 50.0), Some(3.0));
    assert_eq!(percentile(&[1.0, f64::NAN], 50.0), None);
    let s = Summary::of(&v).unwrap();
    assert_eq!((s.count, s.median, s.max), (5, 3.0, 5.0));
    assert!((s.mean - 3.0).abs() < 1e-15);
}
